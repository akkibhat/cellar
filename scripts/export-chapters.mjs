/**
 * Write the chapters out as one Markdown file for editing.
 *
 *   node scripts/export-chapters.mjs
 *
 * WHY
 *
 * The prose lives as strings inside typed block arrays, which is the right
 * shape for the site and the wrong shape for writing. Editing it there means
 * working around quoting and escapes, and a stray apostrophe breaks a build
 * rather than a sentence.
 *
 * So the writing comes out to `_previews/chapters.md`, gets edited there,
 * and goes back in with `scripts/import-chapters.mjs`. The round trip is
 * the point: nothing is retyped by hand on the way home.
 *
 * THE ANCHORS
 *
 * Every editable block is preceded by an HTML comment naming the chapter,
 * its position in that chapter's body, and its kind:
 *
 *     <!-- what-wine-is:4:p -->
 *
 * They do not render, so the file reads as an ordinary document. Leave them
 * alone. The importer matches on them and refuses to guess: move or delete
 * one and it stops rather than writing a paragraph into the wrong chapter.
 *
 * Embedded tools come out read-only. Tables do round-trip, but a cell
 * containing a pipe would gain a column on the way home, so the importer
 * checks every row against the header width and refuses the table if they
 * disagree.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { files, parts } from './reading-order.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const NL = String.fromCharCode(10);

/**
 * Read one chapter file.
 *
 * The content is TypeScript, and node will not import that. Stripping the
 * type import and the one annotation leaves valid JavaScript, which is
 * cheaper and far less brittle than parsing the file ourselves.
 */
async function readChapters(name) {
  const src = fs
    .readFileSync(path.join(ROOT, 'lib', 'content', 'chapters', `${name}.ts`), 'utf8')
    .replace(/^import type .*$/gm, '')
    .replace(/:\s*Chapter\[\]/g, '');
  const tmp = path.join(ROOT, 'node_modules', `.chapters-${name}.mjs`);
  fs.writeFileSync(tmp, src, 'utf8');
  try {
    const mod = await import(pathToFileURL(tmp).href + `?t=${Date.now()}`);
    return Object.values(mod).find(Array.isArray);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

const anchor = (slug, i, kind, extra = '') =>
  `<!-- ${slug}:${i}:${kind}${extra ? ' ' + extra : ''} -->`;

function renderBlock(slug, i, b, out) {
  switch (b.kind) {
    case 'p':
      out.push(anchor(slug, i, 'p'), '', b.text, '');
      break;
    case 'h':
      out.push(anchor(slug, i, 'h'), '', `#### ${b.text}`, '');
      break;
    case 'descriptors':
      out.push(anchor(slug, i, 'descriptors'), '', `*${b.text}*`, '');
      break;
    case 'list':
    case 'steps': {
      out.push(anchor(slug, i, b.kind), '');
      b.items.forEach((it, n) =>
        out.push(b.kind === 'steps' ? `${n + 1}. ${it}` : `- ${it}`),
      );
      out.push('');
      break;
    }
    case 'note':
    case 'unsure':
      out.push(anchor(slug, i, b.kind), '');
      if (b.title) out.push(`> **${b.title}**`, '>');
      out.push(`> ${b.text}`, '');
      break;
    case 'quote':
      out.push(anchor(slug, i, 'quote'), '', `> ${b.text}`, `> — ${b.cite}`, '');
      break;
    case 'table':
      out.push(anchor(slug, i, 'table'), '');
      out.push(`| ${b.head.join(' | ')} |`);
      out.push(`| ${b.head.map(() => '---').join(' | ')} |`);
      b.rows.forEach((r) => out.push(`| ${r.join(' | ')} |`));
      out.push('');
      break;
    case 'tool':
      out.push(anchor(slug, i, 'tool', `READ-ONLY ${b.tool}`), '');
      out.push(`*[the ${b.tool} tool renders here]*`, '');
      break;
    default:
      throw new Error(`unhandled block kind ${b.kind} in ${slug}`);
  }
}

const PARTS = await parts();
const FILES = files();

const chapters = [];
for (const f of FILES) chapters.push(...(await readChapters(f)));

const preamble = [
  '# Cellarbook, for editing',
  '',
  `Generated by \`scripts/export-chapters.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  'One file per part. Edit the prose here, then run',
  '`node scripts/import-chapters.mjs` to write every part back into',
  '`lib/content/chapters/`, or pass one file to import just that part.',
  'Leave the `<!-- anchors -->` alone: they do not render, and the importer',
  'uses them to know where each block belongs.',
  '',
  'Embedded tools are marked READ-ONLY and ignored on the way back. Tables do',
  'come back: keep the pipes lined up and do not put one inside a cell.',
  '',
  '---',
  '',
];

const OUT_DIR = path.join(ROOT, '_previews', 'chapters');
fs.mkdirSync(OUT_DIR, { recursive: true });

/* Anything left from a part that has since been renamed or merged would
   otherwise sit there being imported for ever. */
for (const stale of fs.readdirSync(OUT_DIR)) {
  if (stale.endsWith('.md')) fs.rmSync(path.join(OUT_DIR, stale));
}

let written = 0;
for (const [index, [slug, numeral, title]] of PARTS.entries()) {
  const inPart = chapters.filter((c) => c.part === slug);
  if (!inPart.length) continue;

  const out = [...preamble, `## ${numeral} · ${title}`, ''];
  for (const c of inPart) {
    out.push(`### ${c.n} · ${c.title}`, '');
    out.push(`\`${c.slug}\` · ${c.minutes} min`, '');
    out.push(anchor(c.slug, 'standfirst', 'standfirst'), '', `*${c.standfirst}*`, '');
    c.body.forEach((b, i) => renderBlock(c.slug, i, b, out));
    out.push('---', '');
  }

  /* Numbered so the directory lists in reading order rather than
     alphabetically, which would put Tasting before Foundations. */
  const name = `${String(index + 1).padStart(2, '0')}-${slug}.md`;
  fs.writeFileSync(path.join(OUT_DIR, name), out.join(NL), 'utf8');
  written++;
}

const words = chapters.reduce(
  (n, c) =>
    n +
    c.standfirst.split(/\s+/).length +
    c.body.reduce((m, b) => m + ((b.text ?? b.items?.join(' ') ?? '').split(/\s+/).length), 0),
  0,
);
console.log(
  `${chapters.length} chapters, ~${words.toLocaleString()} words -> `
  + `${written} files in ${path.relative(ROOT, OUT_DIR)}`,
);
